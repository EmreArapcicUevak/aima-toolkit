def test_moves(game, state, expected_moves):
    expected_moves_list = list(expected_moves)
    generated_moves = list(game.ACTIONS(state))

    for action in generated_moves:
        assert action in expected_moves_list, f"Unexpected move generated: {action}"
        expected_moves_list.remove(action)

    assert expected_moves_list == [], f"Missing moves: {expected_moves_list}"


def apply(game, state, move):
  """Helper: apply move and unpack"""
  new_state = game.RESULTS( state, move )
  assert isinstance( new_state, tuple )
  assert len( new_state ) == 4
  board, player, castling, ep = new_state
  assert isinstance( board, tuple )
  assert len( board ) == 64
  assert player in (0, 1)
  assert isinstance( castling, tuple )
  assert len( castling ) == 4
  return board, player, castling, ep


