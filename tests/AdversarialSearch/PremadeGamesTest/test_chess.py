  board, player, castling, ep = apply( game, state, move )

  for check in checks:
    kind = check[ 0 ]

    if kind == "piece":
      _, idx, expected_piece = check
      assert board[ idx ] == expected_piece, f"Square {idx} expected {expected_piece} got {board[ idx ]}"

    elif kind == "player":
      _, expected_player = check
      assert player == expected_player

    elif kind == "ep":
      _, expected_ep = check
      assert ep == expected_ep

    elif kind == "castling":
      _, expected_castling = check
      assert castling == expected_castling

    else:
      raise ValueError( f"Unknown check type: {kind}" )


